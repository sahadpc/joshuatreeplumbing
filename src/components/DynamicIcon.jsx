/**
 * Renders an optimized Lucide icon dynamically by string name
 * with a fallback to Wrench if the icon is not mapped.
 */
export const DynamicIcon = ({ name, className = "w-6 h-6", ...props }) => {
  const IconComponent = iconMap[name] || Wrench;
  return <IconComponent className={className} {...props} />;
};

export default DynamicIcon;
